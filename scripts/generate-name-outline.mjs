// Converts the site name into glyph outlines from Geist Bold so the watermark
// can be drawn as an SVG path instead of SVG text. Paths are not LCP
// candidates and do not wait for the web font, unlike <text>.
//
// Run after changing the name in src/config/site.ts:
//   node scripts/generate-name-outline.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import opentype from "opentype.js";

const { parse } = opentype;
const root = fileURLToPath(new URL("..", import.meta.url));

// The name lives in a TypeScript module, so read it with a regex rather
// than importing it.
const config = readFileSync(`${root}/src/config/site.ts`, "utf8");
const name = config.match(/name:\s*"([^"]+)"/)?.[1];
if (!name) throw new Error("Could not read site.name from src/config/site.ts");

// Not on the package's export map, so resolved by path.
const fontPath = `${root}/node_modules/geist/dist/fonts/geist-sans/Geist-Bold.ttf`;
const bytes = readFileSync(fontPath);
const font = parse(
  bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength),
);

const size = font.unitsPerEm;
const options = { kerning: true, letterSpacing: -0.04 };
const path = font.getPath(name, 0, font.ascender, size, options);
const width = Math.ceil(font.getAdvanceWidth(name, size, options));
const height = font.ascender - font.descender;

const out = `// Generated by scripts/generate-name-outline.mjs. Do not edit.
// Outline of "${name}" in Geist Bold, ${size} units per em.
export const nameOutline = {
  width: ${width},
  height: ${height},
  path: "${path.toPathData(0)}",
} as const;
`;

writeFileSync(`${root}/src/components/layout/name-outline.ts`, out);
console.log(`Wrote name-outline.ts (${out.length} bytes) for "${name}"`);
